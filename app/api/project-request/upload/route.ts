import { checkOrigin, client, errorResponse, launchApi, PRIVATE_HEADERS, rateLimit, readBoundedBody, readJson, RequestError, secret, sessionId } from "@/lib/lead-server";
import { fileError, matchesSignature, MAX_FILE_BYTES, UUID } from "@/lib/project-request";
export const runtime = "nodejs";
export const maxDuration = 60;
export async function POST(request: Request) {
  try {
    checkOrigin(request);
    const session = await sessionId();
    await rateLimit(request, "upload", session);
    const key = process.env.IMAGE_KIT_SECRET_KEY;
    if (!key) throw new RequestError("uploadUnavailable", 503);
    const bytes = await readBoundedBody(request, MAX_FILE_BYTES + 16_384);
    const form = await new Response(bytes, { headers: { "Content-Type": request.headers.get("content-type") || "" } }).formData();
    const file = form.get("file"); const uploadId = String(form.get("uploadId") || "");
    if (!(file instanceof File) || !UUID.test(uploadId)) throw new RequestError("invalid");
    const invalid = fileError(file); if (invalid) throw new RequestError(invalid);
    if (!matchesSignature(file.type, new Uint8Array(await file.slice(0,16).arrayBuffer()))) throw new RequestError("fileType");
    const args = { secret: secret(), sessionId: session, uploadId };
    const reservation = await client().mutation(launchApi.reserveUpload, { ...args, name: file.name.slice(0,180), type: file.type, size: file.size });
    if (reservation.completed) return Response.json({ uploadId }, { headers: PRIVATE_HEADERS });
    const path = reservation.filePath as string;
    const authorization = `Basic ${Buffer.from(`${key}:`).toString("base64")}`;
    // Reconcile an upload whose provider response/completion acknowledgement was
    // lost. The deterministic UUID path is generated by the backend, not the user.
    const lookup = new URL("https://api.imagekit.io/v1/files");
    lookup.searchParams.set("path", path.slice(0, path.lastIndexOf("/")));
    lookup.searchParams.set("searchQuery", `name = "${path.split("/").pop()}"`);
    lookup.searchParams.set("limit", "2");
    const existingResponse = await fetch(lookup, { headers: { Authorization: authorization }, signal: AbortSignal.timeout(10000), cache: "no-store" });
    if (!existingResponse.ok) throw new RequestError("uploadFailed", 502);
    const existingFiles = await existingResponse.json();
    const existing = Array.isArray(existingFiles) ? existingFiles.find(file => file.filePath === path) : null;
    if (existing) {
      if (existing.isPrivateFile !== true || existing.size !== file.size || typeof existing.fileId !== "string") throw new RequestError("uploadFailed", 502);
      await client().mutation(launchApi.completeUpload, { ...args, fileId: existing.fileId, filePath: path });
      return Response.json({ uploadId }, { headers: PRIVATE_HEADERS });
    }
    const upload = new FormData();
    upload.set("file", file);
    upload.set("fileName", path.split("/").pop()!);
    upload.set("folder", path.slice(0,path.lastIndexOf("/")));
    upload.set("isPrivateFile", "true");
    upload.set("useUniqueFileName", "false");
    upload.set("overwriteFile", "false");
    const response = await fetch("https://upload.imagekit.io/api/v1/files/upload", {
      method: "POST", headers: { Authorization: authorization }, body: upload,
      signal: AbortSignal.timeout(40_000),
    });
    if (!response.ok) throw new RequestError("uploadFailed", 502);
    const result = await response.json();
    if (typeof result.fileId !== "string" || result.filePath !== path) throw new RequestError("uploadFailed", 502);
    await client().mutation(launchApi.completeUpload, { ...args, fileId: result.fileId, filePath: path });
    return Response.json({ uploadId }, { headers: PRIVATE_HEADERS });
  } catch (error) { return errorResponse(error); }
}
export async function DELETE(request: Request) {
  try {
    checkOrigin(request);
    const session = await sessionId();
    const body = await readJson(request, 512);
    if (!UUID.test(body?.uploadId || "")) throw new RequestError("invalid");
    await client().mutation(launchApi.cancelUpload, { secret: secret(), sessionId: session, uploadId: body.uploadId });
    return Response.json({ ok: true }, { headers: PRIVATE_HEADERS });
  } catch (error) { return errorResponse(error); }
}
